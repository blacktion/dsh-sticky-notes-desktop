/**
 * Render `electron/note.html` in a real window and screenshot it.
 *
 * The note window is the one surface that no unit test can judge: its whole
 * contract is "is this readable at this size and transparency". This harness
 * loads the real page with the real stylesheet and stands in for the preload,
 * so a contrast problem — dark title-bar buttons on a black note, a grip you
 * cannot see — shows up as a picture instead of a guess.
 *
 * Usage: node tools/render-note.mjs <case> [outDir]
 *
 * One case per process: reusing a destroyed `BrowserWindow`'s session for a
 * second `loadFile` fails with ERR_FAILED, and a fresh process is also a truer
 * stand-in for a real note window (which owns its own process).
 *
 * @module dsh-sticky-notes-desktop/tools/render-note
 */
import { app, BrowserWindow, ipcMain } from 'electron';
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const ELECTRON_DIR = join(HERE, '..', 'electron');

const CASE_NAME = process.argv[2] ?? 'default-black';
const outDir = process.argv[3] ?? join(HERE, '.render');
mkdirSync(outDir, { recursive: true });

/** The appearances worth looking at: the new default, plus a light one. */
const CASES = {
  'default-black': { color: '#000000', opacity: 0.8, textColor: '#f5f5f5' },
  'classic-yellow': { color: '#fff3b0', opacity: 1, textColor: '#3b3320' },
  blue: { color: '#bbdefb', opacity: 0.9, textColor: '#10243a' },
  // The reported bug: a body colour that clashes with the note. The *body* will be hard to read — that
  // is the user's own choice and not ours to override — but the toolbar controls must stay legible
  // regardless, so this case deliberately does not assert the body contrast.
  'dark-ink-on-black': { color: '#000000', opacity: 0.8, textColor: '#222222', expectBodyContrast: false },
  // Reference render for `docs/note-black.png`, at the size a new note actually opens at
  // (`DEFAULT_NOTE_WIDTH`/`DEFAULT_NOTE_HEIGHT` in lib/host/geometry.js). Kept in the case table so the
  // screenshot in the README can be regenerated by name instead of by remembered command-line flags.
  'docs-default': {
    color: '#000000',
    opacity: 0.8,
    textColor: '#f5f5f5',
    width: 300,
    height: 200,
  },
};

const note = CASES[CASE_NAME];
if (note === undefined) {
  console.error(`未知用例：${CASE_NAME}（可用：${Object.keys(CASES).join(', ')}）`);
  app.exit(2);
}

/**
 * Stand in for `electron/preload-note.cjs`.
 *
 * The page talks to the main process only through `window.sticky`; the minimal
 * set below is enough for a first paint, which is all this harness inspects.
 */
function installStub() {
  ipcMain.handle('note:init', () => ({
    note: {
      id: 'render-note',
      kind: 'text',
      title: '便签标题',
      text: '这是一条便签的正文示例。\n第二行用来检查行距与滚动区域。',
      hidden: false,
      edge: null,
      fontSize: 14,
      alwaysOnTop: true,
      ...note,
    },
    settings: { fontSize: 14 },
  }));
  for (const channel of [
    'note:save',
    'note:update',
    'note:close',
    'note:delete',
    'note:hide',
    'note:pickColor',
    'note:exportImage',
    'note:commitText',
    'note:setBounds',
    'note:setSize',
    'note:dragState',
  ]) {
    ipcMain.handle(channel, () => ({ ok: true }));
  }
}

/**
 * Relative luminance of an `rgb(...)` string, per WCAG.
 * @param {string} rgb
 * @returns {number}
 */
function luminanceOf(rgb) {
  const parts = String(rgb).match(/\d+(\.\d+)?/g);
  if (parts === null || parts.length < 3) return 0;
  const [r, g, b] = parts.slice(0, 3).map((value) => {
    const channel = Number(value) / 255;
    return channel <= 0.03928 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/** WCAG contrast ratio between two luminances. */
function contrastRatio(a, b) {
  const lighter = Math.max(a, b);
  const darker = Math.min(a, b);
  return (lighter + 0.05) / (darker + 0.05);
}

/** Parse `#rrggbb` into `rgb(...)` so it can be compared with computed styles. */
function toRgb(hex) {
  const value = String(hex).replace('#', '');
  const full =
    value.length === 3
      ? value[0] + value[0] + value[1] + value[1] + value[2] + value[2]
      : value;
  return `rgb(${parseInt(full.slice(0, 2), 16)}, ${parseInt(full.slice(2, 4), 16)}, ${parseInt(full.slice(4, 6), 16)})`;
}

app.commandLine.appendSwitch('disable-gpu-compositing-cache');

app.whenReady().then(async () => {
  installStub();

  const window = new BrowserWindow({
    // A case may pin its own size; otherwise the harness default, which the appearance test relies on.
    width: note.width ?? 280,
    height: note.height ?? 220,
    frame: false,
    transparent: true,
    hasShadow: false,
    show: false,
    backgroundColor: '#00000000',
    webPreferences: {
      preload: join(ELECTRON_DIR, 'preload-note.cjs'),
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: true,
    },
  });

  await window.loadFile(join(ELECTRON_DIR, 'note.html'));
  await new Promise((resolve) => setTimeout(resolve, 1000));

  // Report the colours the page actually resolved, so a contrast problem can be
  // attributed to the stylesheet, the variables, or the initial state.
  const probe = await window.webContents.executeJavaScript(`(() => {
    const app = document.getElementById('app');
    const style = getComputedStyle(app);
    const button = document.getElementById('btn-save');
    const draft = document.getElementById('draft-mark');
    const root = getComputedStyle(document.documentElement);
    return {
      noteFg: style.getPropertyValue('--note-fg').trim(),
      noteBgColor: style.getPropertyValue('--note-bg-color').trim(),
      bodyColor: getComputedStyle(document.body).color,
      buttonColor: getComputedStyle(button).color,
      titleColor: getComputedStyle(document.getElementById('title-input')).color,
      gripColor: style.getPropertyValue('--note-grip').trim(),
      fallbackHidden: document.getElementById('fallback').hasAttribute('hidden'),
      // The toolbar ink and the tint derived from it. Both are computed per note from the background.
      ink: root.getPropertyValue('--note-ink').trim(),
      btnBg: root.getPropertyValue('--note-btn-bg').trim(),
      draftColor: draft === null ? null : getComputedStyle(draft).color,
      deleteColor: getComputedStyle(document.getElementById('btn-delete')).color,
      hideColor: getComputedStyle(document.getElementById('btn-hide')).color,
      closeColor: getComputedStyle(document.getElementById('btn-close')).color,
      // Secondary furniture: the type mark, the title-bar divider and the placeholders. These are not
      // controls, so they are checked for a lower contrast floor than the buttons.
      dotColor: getComputedStyle(document.querySelector('.kind-dot')).backgroundColor,
      divider: getComputedStyle(document.getElementById('titlebar')).borderBottomColor,
      titlePlaceholder: root.getPropertyValue('--note-ink-soft').trim(),
      editorPlaceholder: root.getPropertyValue('--note-ink-soft').trim(),
    };
  })()`);
  console.log(`  ${CASE_NAME} computed:`, JSON.stringify(probe));

  const image = await window.webContents.capturePage();
  const target = join(outDir, `${CASE_NAME}.png`);
  writeFileSync(target, image.toPNG());
  console.log(`${CASE_NAME}: ${image.getSize().width}x${image.getSize().height} → ${target}`);

  // The note's own text colour must reach the *body*. `body` declares the text colour and every text
  // element inherits from it, so appearance variables declared lower (on `#app`, say) would be invisible
  // to it and everything would silently fall back to the dark default.
  const expected = toRgb(note.textColor);
  const problems = [];
  if (probe.bodyColor !== expected) problems.push(`body 正文色 ${probe.bodyColor} ≠ ${expected}`);
  if (probe.titleColor !== expected) problems.push(`标题输入色 ${probe.titleColor} ≠ ${expected}`);
  if (probe.noteFg !== note.textColor) problems.push(`--note-fg ${probe.noteFg} ≠ ${note.textColor}`);
  if (probe.fallbackHidden !== true) problems.push('降级提示条意外显示');

  // -------------------------------------------------------------------------------------------
  // The toolbar's controls are the one place the configured text colour must NOT be used.
  //
  // They are buttons: their legibility cannot depend on a decorative setting, or a dark body colour on
  // a black note makes 「保存」/「关闭」 invisible. They get their own ink — pure white or pure black,
  // whichever contrasts with the note's background.
  // -------------------------------------------------------------------------------------------
  const WHITE = 'rgb(255, 255, 255)';
  const BLACK = 'rgb(17, 17, 17)';
  if (probe.buttonColor !== WHITE && probe.buttonColor !== BLACK) {
    problems.push(`标题栏按钮色必须只取纯白或纯黑，实际 ${probe.buttonColor}`);
  }

  /**
   * Contrast of the ink against the note as it is actually painted.
   *
   * The background layer is semi-transparent, so what shows through depends on the desktop behind it.
   * Both extremes are evaluated and the *better* one is reported as the guarantee, which is the property
   * worth having: legible whatever wallpaper is behind the note. Checking a single mid-grey assumption
   * would pass on a light desktop and fail on a dark one.
   */
  const noteChannels = toRgb(note.color).match(/\d+/g).map(Number);
  const inkLum = luminanceOf(probe.buttonColor);
  const worstInkContrast = Math.max(
    ...[255, 0].map((back) => {
      const painted = noteChannels.map((c) => c * note.opacity + back * (1 - note.opacity));
      const lum = luminanceOf(`rgb(${painted.map((v) => Math.round(v)).join(',')})`);
      return contrastRatio(inkLum, lum);
    }),
  );
  if (worstInkContrast < 4.5) {
    problems.push(`按钮文字对比度只有 ${worstInkContrast.toFixed(2)}:1，低于 4.5:1（墨色 ${probe.buttonColor}）`);
  }

  // Every toolbar button must agree, and so must the draft badge: one of them keeping the old
  // inherited colour is exactly the bug this guards.
  for (const [name, value] of [
    ['保存', probe.buttonColor],
    ['保留', probe.hideColor],
    ['关闭', probe.closeColor],
    ['删除', probe.deleteColor],
    ['未保存', probe.draftColor],
  ]) {
    if (value !== probe.buttonColor) problems.push(`「${name}」的颜色 ${value} 与其它按钮 ${probe.buttonColor} 不一致`);
  }

  if (note.textColor === '#f5f5f5' && note.color === '#000000' && probe.buttonColor !== WHITE) {
    problems.push('黑底便签的按钮应当是白字');
  }

  // -------------------------------------------------------------------------------------------
  // Secondary furniture — the type mark, the divider and the placeholders.
  //
  // Same reasoning as the buttons (they must not vanish if the body colour happens to match the note),
  // but a *lower* floor: these are not controls, so they are allowed to sit back rather than shout. The
  // floor is 2.5:1 — visible at a glance on any wallpaper, without competing with the button labels.
  //
  // Each is a translucent layer of the ink painted over the note, so the comparison is the composited
  // result against the note itself. Getting that wrong in either direction is easy: comparing the raw
  // ink would flatter it, and compositing the ink twice would damn it.
  // -------------------------------------------------------------------------------------------
  const alphaOf = (value) => {
    const m = String(value).match(/rgba?\([^)]*?,\s*([\d.]+)\s*\)/);
    return m === null ? 1 : Number(m[1]);
  };
  const inks = (value) => {
    const parts = String(value).match(/[\d.]+/g).map(Number);
    return parts.slice(0, 3);
  };

  for (const back of [255, 0]) {
    const painted = noteChannels.map((c) => c * note.opacity + back * (1 - note.opacity));
    const bgLum = luminanceOf(`rgb(${painted.map((v) => Math.round(v)).join(',')})`);

    // The title bar carries its own overlay (`--note-bar-bg`, the note colour at 35%), and the divider
    // is drawn on top of *that*, not on the note. Measuring it against the note would overstate the
    // contrast by roughly a third — enough to pass a divider that is actually invisible.
    const bar = painted.map((c) => c * 0.65);
    const barLum = luminanceOf(`rgb(${bar.map((v) => Math.round(v)).join(',')})`);

    // Each element is composited over the surface it is actually painted on, and measured against that
    // same surface. The divider sits on the title bar's overlay; the mark and the placeholders sit on
    // the note. Using one backdrop for all of them was wrong in both directions.
    const layers = [
      ['类型标记', probe.dotColor, painted, bgLum],
      ['标题栏分割线', probe.divider, bar, barLum],
      ['输入内容提示', probe.titlePlaceholder, painted, bgLum],
    ];
    for (const [name, value, surface, against] of layers) {
      const alpha = alphaOf(value);
      const rgb = inks(value);
      const composited = surface.map((v, i) => v * (1 - alpha) + rgb[i] * alpha);
      const ratio = contrastRatio(
        luminanceOf(`rgb(${composited.map((v) => Math.round(v)).join(',')})`),
        against,
      );
      if (ratio < 2.5) {
        problems.push(`${name} 对比度只有 ${ratio.toFixed(2)}:1，低于 2.5:1`);
      }
    }
  }

  // The softer family must stay softer: if a furniture colour came out fully opaque it would have
  // drifted into the button ink, and "readable but not as loud as the buttons" would be lost.
  const placeholderAlpha = alphaOf(probe.titlePlaceholder);
  if (!(placeholderAlpha > 0 && placeholderAlpha < 1)) {
    problems.push(`输入内容提示应当是半透明的柔和墨色，实际 ${probe.titlePlaceholder}`);
  }

  // -------------------------------------------------------------------------------------------
  // The furniture must be derived from the note's *background*, not from the configured text colour.
  //
  // Contrast alone cannot catch this: on a black note a dark body colour happens to sit far enough from
  // the background to pass a 2.5:1 floor, so the mark would look "fine" while still being the wrong
  // thing — and it would vanish on any note whose body colour is close to its background, which is the
  // whole point. So this asserts the actual property: the colour comes from the ink family.
  //
  // The divider and the placeholders are drawn straight from the ink variables, so for them the
  // check is exact. The type mark is the ink at an alpha set in CSS, so it is compared by hue instead.
  const configured = toRgb(note.textColor);
  const configuredParts = configured.match(/\d+/g).map(Number);
  if (probe.buttonColor === configured) {
    problems.push('按钮颜色不应等于正文颜色');
  }
  for (const [name, value] of [
    ['标题栏分割线', probe.divider],
    ['输入内容提示', probe.titlePlaceholder],
  ]) {
    const parts = String(value).match(/[\d.]+/g).map(Number).slice(0, 3);
    if (parts.length === 3 && parts.every((v, i) => v === configuredParts[i])) {
      problems.push(`${name} 不应等于正文颜色 ${configured}`);
    }
  }

  const noteLum = luminanceOf(toRgb(note.color));
  const ratio = contrastRatio(luminanceOf(expected), noteLum);
  // Skipped for the case that deliberately clashes, so its failure stays about the buttons.
  if (note.expectBodyContrast !== false && ratio < 4.5) {
    problems.push(`正文/背景对比度仅 ${ratio.toFixed(2)}:1，低于 4.5:1`);
  }

  if (problems.length > 0) {
    console.error(`${CASE_NAME}: 外观检查失败`);
    for (const problem of problems) console.error(`  - ${problem}`);
    app.exit(1);
    return;
  }
  console.log(
    `${CASE_NAME}: 外观检查通过（正文对比度 ${ratio.toFixed(2)}:1，按钮文字 ${probe.buttonColor}，最差 ${worstInkContrast.toFixed(2)}:1）`,
  );
  app.quit();
});
